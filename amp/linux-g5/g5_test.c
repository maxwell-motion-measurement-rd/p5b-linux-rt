#define _POSIX_C_SOURCE 200809L
#include <errno.h>
#include <fcntl.h>
#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <time.h>
#include <unistd.h>
#include "../protocol/amp_wire.h"
static int fd,peer_seen;
static uint32_t sequence, peer_sequence;
static uint64_t session, epoch;
static uint8_t tx[AMP_FRAME_MAX], rx[AMP_FRAME_MAX];
static uint64_t now_ns(void)
{
    struct timespec t;
    if(clock_gettime(CLOCK_MONOTONIC,&t)) {perror("clock_gettime");exit(1);}
    return (uint64_t)t.tv_sec*1000000000ULL+t.tv_nsec;
}
static void fail(const char *why) { fprintf(stderr,"G5_FAIL seq=%u: %s errno=%d\n",sequence,why,errno);exit(1); }
static struct amp_view transact(unsigned type,const uint8_t *p,unsigned n,uint32_t correlation)
{
    struct amp_view v={0},got;
    int bytes,received;
    v.type=type;v.seq=++sequence;v.correlation=correlation;v.session=session;
    v.epoch=type==AMP_HELLO?0:epoch;v.payload_len=n;v.payload=p;
    bytes=amp_encode(tx,sizeof(tx),&v);
    if(bytes<0 || write(fd,tx,bytes)!=bytes) fail("write/frame encode");
    received=read(fd,rx,sizeof(rx));
    if(received<0 || amp_decode(rx,(size_t)received,&got)) fail("read/frame decode");
    if(got.session!=session || (epoch && got.epoch!=epoch)) fail("session/epoch");
    if(peer_seen && got.seq!=peer_sequence+1U) fail("peer sequence");
    peer_sequence=got.seq;peer_seen=1;
    return got;
}
static int compare_u64(const void *a,const void *b)
{
    uint64_t x=*(const uint64_t *)a,y=*(const uint64_t *)b;
    return (x>y)-(x<y);
}
static uint64_t percentile(const uint64_t *a,unsigned n,unsigned p)
{
    unsigned i=(n*p+999)/1000;
    return a[(i?i:1)-1]/1000;
}
int main(int argc,char **argv)
{
    static const unsigned lengths[]={0,1,4,63,64,65,255,256};
    unsigned mode=0,n=60000,i,j,len,pattern;
    uint32_t rng;
    uint8_t payload[256];
    uint64_t *latency,sum=0,begin,next,missed=0;
    struct amp_view got;
    const char *label;
    FILE *evidence;
    char path[128],*end;
    if(argc<2 || argc>3) {fprintf(stderr,"usage: g3_test forward|reverse|cross [count<=60000]\n");return 2;}
    if(!strcmp(argv[1],"forward")) mode=AMP_ECHO_REQ;
    else if(!strcmp(argv[1],"reverse")) mode=AMP_ARM_REVERSE;
    else if(!strcmp(argv[1],"cross")) mode=AMP_CROSSED;
    else return 2;
    label=argv[1];
    if(argc==3) {errno=0;n=(unsigned)strtoul(argv[2],&end,10);if(errno||*end||!n||n>60000)return 2;}
    latency=calloc(n,sizeof(*latency));if(!latency)fail("allocate");
    fd=open("/dev/p5-core3",O_RDWR);if(fd<0)fail("open exclusive device");
    session=now_ns();if(!session)session=1;
    got=transact(AMP_HELLO,0,0,0);
    if(got.type!=AMP_READY || got.correlation!=sequence || got.payload_len || !got.epoch)fail("HELLO/READY");
    epoch=got.epoch;
    begin=next=now_ns();
    for(i=0;i<n;i++) {
        uint64_t t0,t1,late;
        uint32_t origin;
        struct timespec wake;
        len=lengths[i%8];pattern=(i/8)%6;rng=0x12345678U^i;
        for(j=0;j<len;j++) {
            rng^=rng<<13;rng^=rng>>17;rng^=rng<<5;
            payload[j]=pattern==0?0:pattern==1?255:pattern==2?0x55:pattern==3?0xaa:pattern==4?(uint8_t)j:(uint8_t)rng;
        }
        t0=now_ns();origin=sequence+1U;
        got=transact(mode,payload,len,0);
        if(got.correlation!=origin)fail("origin correlation");
        if(mode==AMP_ECHO_REQ) {
            if(got.type!=AMP_ECHO_RESP || got.payload_len!=len || memcmp(got.payload,payload,len))fail("forward bytes");
        } else {
            uint32_t reverse=got.seq;
            if(got.type!=AMP_ECHO_REQ || got.payload_len!=len)fail("reverse request");
            for(j=0;j<len;j++)if(got.payload[j]!=(uint8_t)(j^reverse^0xa5U))fail("reverse generated bytes");
            got=transact(AMP_ECHO_RESP,got.payload,len,reverse);
            if(got.correlation!=origin)fail("completion correlation");
            if(mode==AMP_CROSSED) {
                if(got.type!=AMP_ECHO_RESP || got.payload_len!=len || memcmp(got.payload,payload,len))fail("crossed bytes");
            } else if(got.type!=AMP_READY || got.payload_len)fail("reverse completion");
        }
        t1=now_ns();latency[i]=t1-t0;sum+=latency[i];
        if((i+1)%1000==0)fprintf(stderr,"G5_PROGRESS %s %u/%u\n",label,i+1,n);
        next+=10000000ULL;
        if(t1>next) {late=(t1-next)/10000000ULL+1;missed+=late;next+=late*10000000ULL;}
        wake.tv_sec=next/1000000000ULL;wake.tv_nsec=next%1000000000ULL;
        if(clock_nanosleep(CLOCK_MONOTONIC,TIMER_ABSTIME,&wake,0))fail("rate pacing");
    }
    snprintf(path,sizeof(path),"/tmp/amp-g5-%s.latency-ns",label);
    evidence=fopen(path,"w");if(!evidence)fail("latency evidence");
    for(i=0;i<n;i++)if(fprintf(evidence,"%u %" PRIu64 "\n",i,latency[i])<0)fail("latency write");
    if(fclose(evidence))fail("latency close");
    qsort(latency,n,sizeof(*latency),compare_u64);
    printf("{\"mode\":\"%s\",\"passed\":%u,\"errors\":0,\"elapsed_ns\":%" PRIu64 ",\"missed_release\":%" PRIu64 ",\"session\":%" PRIu64 ",\"epoch\":%" PRIu64 ",\"min_us\":%" PRIu64 ",\"mean_us\":%" PRIu64 ",\"p50_us\":%" PRIu64 ",\"p95_us\":%" PRIu64 ",\"p99_us\":%" PRIu64 ",\"p999_us\":%" PRIu64 ",\"max_us\":%" PRIu64 "}\n",
        label,n,now_ns()-begin,missed,session,epoch,latency[0]/1000,sum/n/1000,
        percentile(latency,n,500),percentile(latency,n,950),percentile(latency,n,990),percentile(latency,n,999),latency[n-1]/1000);
    close(fd);free(latency);return 0;
}
